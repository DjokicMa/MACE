"""Job folders and scratch directories whose path has a space.

The job scripts expanded $DIR and $scratch unquoted (`cp $DIR/$JOB.d12
$scratch/$JOB/INPUT`, `cd $scratch/$JOB`, `>& $DIR/${JOB}.out`), so a deck in
"my calcs/" staged nothing and wrote no output. They are quoted now (checked
with shellcheck where it is installed).

A deck NAME with a space or a shell character ("si (copy).d12") cannot be a
SLURM job name or the `export JOB=` of the script: `mace submit` refuses it
up front and exits non-zero, like `mace run`.

The scripts are generated by the real generators and run with bash, with a
stub mpirun; `mace submit` runs as a subprocess against tests/fake_slurm.py.
"""
import json
import shutil
import stat
import subprocess
from pathlib import Path

import pytest

from fake_slurm import FakeSlurm
from test_array_default_path_golden import BAND_D3, SP_D12
from test_scratch_guard import DECK, NO_HPCC_USER, _generate
from test_site_jobscript import _env, _mace

STUB = """#!/bin/bash
echo "CWD=$(pwd)" > "$DIR/$JOB.stub"
echo "INPUT=$(wc -c < INPUT)" >> "$DIR/$JOB.stub"
sleep 0.2
echo "computed" > fort.9
[ -f fort.9 ] && echo "band" > BAND.DAT
echo " EEEEEEEEEE TERMINATION  DATE 02 10 2026"
"""


def _run(tmp_path: Path, script: Path, scratch: Path):
    stubs = tmp_path / "stubs"
    stubs.mkdir(exist_ok=True)
    for name, text in (("mpirun", STUB), ("python", "#!/bin/bash\nexit 0\n")):
        p = stubs / name
        p.write_text(text)
        p.chmod(p.stat().st_mode | stat.S_IEXEC)
    env = {"PATH": f"{stubs}:/usr/bin:/bin", "HOME": str(tmp_path), "SLURM_SUBMIT_DIR": str(script.parent),
           "SLURM_NTASKS": "1", "EBROOTCRYSTAL": str(tmp_path), "SCRATCH": str(scratch), "USER": NO_HPCC_USER}
    return subprocess.run(["bash", str(script)], cwd=script.parent, env=env,
                          capture_output=True, text=True, timeout=60)


@pytest.mark.parametrize("kind", ["crystal", "prop"])
def test_folder_and_scratch_with_spaces(tmp_path, kind):
    d = tmp_path / "my calcs"
    d.mkdir()
    scratch = tmp_path / "scratch space"
    if kind == "crystal":
        job, deck = "si", "si.d12"
        (d / deck).write_text(DECK)
    else:
        job, deck = "si_band", "si_band.d3"
        (d / deck).write_text("BAND\nEND\n")
        (d / "si_band.f9").write_text("wavefunction")
    r = _run(tmp_path, _generate(d, kind, job), scratch)
    assert r.returncode == 0, r.stdout + r.stderr
    for bad in ("ambiguous redirect", "No such file", "cannot stat", "too many arguments", "binary operator"):
        assert bad not in r.stdout + r.stderr, r.stdout + r.stderr
    stub = dict(l.split("=", 1) for l in (d / f"{job}.stub").read_text().splitlines())
    sub = "crys23" if kind == "crystal" else "crys23/prop"
    assert stub["CWD"] == str(scratch / sub / job)
    assert int(stub["INPUT"]) > 0
    assert "TERMINATION" in (d / f"{job}.out").read_text()
    assert (d / f"{job}.f9").read_text() == "computed\n"
    if kind == "prop":
        assert (d / "si_band.BAND.DAT").read_text() == "band\n"
    assert (d / f".{job}.scratch").read_text().strip() == str(scratch / sub / job)


SHELL_VARS = ("$DIR", "${DIR}", "$scratch", "${scratch}", "$JOB", "${JOB}", "$SLURM_SUBMIT_DIR")


@pytest.mark.skipif(not shutil.which("shellcheck"), reason="shellcheck not installed")
@pytest.mark.parametrize("kind,job", [("crystal", "si"), ("prop", "si_band")])
def test_generated_scripts_quote_their_paths(tmp_path, kind, job):
    script = _generate(tmp_path, kind, job)
    r = subprocess.run(["shellcheck", "-s", "bash", "-f", "json", "-i", "SC2086", str(script)],
                       capture_output=True, text=True)
    lines = script.read_text().splitlines()
    unquoted = []
    for f in json.loads(r.stdout or "[]"):
        text = lines[f["line"] - 1][f["column"] - 1:]
        if text.startswith(SHELL_VARS):
            unquoted.append(f"{f['line']}: {lines[f['line'] - 1].strip()}")
    assert not unquoted, "\n".join(unquoted)


def _submit_env(tmp_path):
    fake = FakeSlurm(tmp_path / "fs")
    env = _env(tmp_path, PATH=fake.env["PATH"], FAKE_SLURM_STATE=fake.env["FAKE_SLURM_STATE"],
               FAKE_SLURM_LOG=fake.env["FAKE_SLURM_LOG"])
    return env, fake


@pytest.mark.parametrize("extra", [[], ["--nosubmit"]])
def test_deck_name_with_a_space_is_refused(tmp_path, extra):
    env, fake = _submit_env(tmp_path)
    d = tmp_path / "my calcs"
    d.mkdir()
    (d / "si (copy).d12").write_text(SP_D12)
    p = _mace(tmp_path, env, "submit", *extra, "my calcs/si (copy).d12")
    out = p.stdout + p.stderr
    assert p.returncode != 0, out
    assert "si (copy).d12" in out and "Rename the deck" in out
    assert "Submission complete" not in out and "Script generation complete" not in out
    assert not fake.calls("sbatch")
    assert not list(d.glob("*.sh"))


def test_folder_with_a_space_and_one_bad_name(tmp_path):
    """The deck that can run is submitted; the other is refused, and the exit
    status says not everything was submitted."""
    env, fake = _submit_env(tmp_path)
    d = tmp_path / "my calcs"
    d.mkdir()
    (d / "si.d12").write_text(SP_D12)
    (d / "si (copy).d12").write_text(SP_D12)
    (d / "x_band.d3").write_text(BAND_D3)
    (d / "x_band.f9").write_text("wavefunction")
    (d / "x$y_band.d3").write_text(BAND_D3)
    (d / "x$y_band.f9").write_text("wavefunction")
    p = _mace(tmp_path, env, "submit", "my calcs", stdin="3\n")
    out = p.stdout + p.stderr
    assert p.returncode == 1, out
    assert sorted(Path(c["script"]).name for c in fake.calls("sbatch")) == ["si.sh", "x_band.sh"]
    assert "si (copy).d12" in out and "x$y_band.d3" in out


def test_site_launch_settings_still_reach_a_template_copied_by_an_earlier_mace():
    """A workflow_scripts/ copy taken before 1.1.5 has the unquoted output path
    in its CRYSTAL line; the site's [mpi] launcher still replaces it."""
    from mace.submission import site
    legacy = site.LEGACY_LAUNCH_LINES["scf"]
    assert '"$DIR/${JOB}.out"' not in legacy and '"$DIR/${JOB}.out"' in site.LAUNCH_LINES["scf"]
    s = site.Site()
    s.launcher = "srun"
    new, changes, _ = site.customize_generator_text(f"cd x\n{legacy}\ncd y", "scf", s, None)
    assert legacy not in new and any(c.startswith("CRYSTAL launch srun") for c in changes)


@pytest.mark.skipif(not shutil.which("shellcheck"), reason="shellcheck not installed")
@pytest.mark.parametrize("kind,job", [("crystal", "si"), ("prop", "si_band")])
def test_generated_scripts_have_no_unquoted_expansion_or_unchecked_cd(tmp_path, kind, job):
    """Not only paths: `mpirun -n $SLURM_NTASKS $EBROOTCRYSTAL/bin/...` and the
    post-run `cd "$DIR"` were left (SC2086, SC2164)."""
    script = _generate(tmp_path, kind, job)
    r = subprocess.run(["shellcheck", "-s", "bash", "-f", "json", "-i", "SC2086,SC2164", str(script)],
                       capture_output=True, text=True)
    lines = script.read_text().splitlines()
    found = [f"SC{f['code']} {f['line']}: {lines[f['line'] - 1].strip()}" for f in json.loads(r.stdout or "[]")]
    assert not found, "\n".join(found)


@pytest.mark.parametrize("old", [
    'I_MPI_HYDRA_BOOTSTRAP="ssh" mpirun -n $SLURM_NTASKS $EBROOTCRYSTAL/bin/Pcrystal 2>&1 >& "$DIR/${JOB}.out"',
    'I_MPI_HYDRA_BOOTSTRAP="ssh" mpirun -n $SLURM_NTASKS $EBROOTCRYSTAL/bin/Pcrystal 2>&1 >& $DIR/${JOB}.out',
])
def test_site_launch_settings_still_reach_the_unquoted_launch_lines(old):
    """Templates copied into workflow_scripts/ by an earlier MACE (or this
    release's preview) keep their unquoted launch line; [mpi] still reaches it."""
    from mace.submission import site
    s = site.Site()
    s.launcher = "srun"
    new, changes, _ = site.customize_generator_text(f"cd x\n{old}\ncd y", "scf", s, None)
    assert old not in new and any(c.startswith("CRYSTAL launch srun") for c in changes)
    assert '"$EBROOTCRYSTAL/bin/Pcrystal"' in new
