"""Two decks of the same name in different folders must not share a scratch
directory.

The job scripts stage into $SCRATCH/crys23/<job> (properties:
$SCRATCH/crys23/prop/<job>), named after the deck alone. A second x.d12 from
another folder then ran in the first one's directory: at the same time they
overwrite each other's INPUT and fort.9, and one after the other the second
restarted from the first one's OPTINFO.DAT (OPTGEOM RESTART) or fort.20.

The directory now records the folder whose deck uses it; a deck of the same
name from another folder runs in $scratch/.mace_by_dir/<checksum>/<job>. A
deck rerun from its own folder keeps its directory (an OPTGEOM RESTART reads
OPTINFO.DAT and fort.20 there), and a directory without a record (an earlier
MACE, or a fort.20 staged by hand) belongs to the first deck that runs in it.

The scripts are generated by the real generators and run with bash, with a
stub mpirun (tests/test_scratch_guard.py)."""
from pathlib import Path

from mace.recovery import opt_restart
from test_scratch_guard import DECK, NO_HPCC_USER, _generate, _run, _stub

RESTART_DECK = DECK.replace("END\nDFT", "OPTGEOM\nRESTART\nENDOPT\nEND\nDFT", 1)


def _folder(tmp_path: Path, name: str, deck: str, text: str) -> Path:
    d = tmp_path / name
    d.mkdir()
    (d / deck).write_text(text)
    return d


def test_same_named_decks_in_two_folders_get_their_own_scratch(tmp_path):
    scratch = tmp_path / "scr"
    scratch.mkdir()
    env = {"SCRATCH": str(scratch), "USER": NO_HPCC_USER}
    one = _folder(tmp_path, "one", "x.d12", RESTART_DECK)
    two = _folder(tmp_path, "two", "x.d12", RESTART_DECK)

    r1 = _run(tmp_path, _generate(one, "crystal", "x"), env)
    assert r1.returncode == 0, r1.stdout + r1.stderr
    shared = scratch / "crys23" / "x"
    assert _stub(one, "x")["CWD"] == str(shared)                 # unchanged for the first deck
    # one's optimization was killed: its history is in its directory
    (shared / "OPTINFO.DAT").write_text("history of one/x")

    r2 = _run(tmp_path, _generate(two, "crystal", "x"), env)
    assert r2.returncode == 0, r2.stdout + r2.stderr
    cwd2 = Path(_stub(two, "x")["CWD"])
    assert cwd2 != shared and cwd2.name == "x"
    assert cwd2.parent.parent == scratch / "crys23" / ".mace_by_dir"
    # two never continues one's optimization
    assert "RESTART requested but no OPTINFO.DAT" in r2.stdout
    assert "belongs to x in" in r2.stdout
    assert (shared / "OPTINFO.DAT").read_text() == "history of one/x"
    # the recovery looks where two ran
    assert (two / ".x.scratch").read_text().strip() == str(cwd2)
    assert opt_restart.job_scratch_dir("", "x", submit_dir=two) == cwd2

    # one's rerun still continues from its own history, in its own directory
    r3 = _run(tmp_path, one / "x.sh", env)
    assert r3.returncode == 0, r3.stdout + r3.stderr
    assert _stub(one, "x")["CWD"] == str(shared)
    assert "RESTART: continuing the optimization from OPTINFO.DAT" in r3.stdout
    # and two's rerun finds its own directory again
    (cwd2 / "OPTINFO.DAT").write_text("history of two/x")
    r4 = _run(tmp_path, two / "x.sh", env)
    assert Path(_stub(two, "x")["CWD"]) == cwd2
    assert "RESTART: continuing the optimization from OPTINFO.DAT" in r4.stdout


def test_directory_without_a_record_belongs_to_the_first_deck(tmp_path):
    """A fort.20 staged by hand (or a directory an earlier MACE left) is used
    by the deck that runs there first, as before."""
    scratch = tmp_path / "scr"
    hand = scratch / "crys23" / "x"
    hand.mkdir(parents=True)
    (hand / "fort.20").write_text("staged by hand")
    one = _folder(tmp_path, "one", "x.d12", DECK.replace("DFT", "GUESSP\nDFT", 1))
    r = _run(tmp_path, _generate(one, "crystal", "x"), {"SCRATCH": str(scratch), "USER": NO_HPCC_USER})
    assert r.returncode == 0, r.stdout + r.stderr
    assert _stub(one, "x")["CWD"] == str(hand)
    assert "kept the fort.20 already in" in r.stdout
    assert (hand / ".mace_submit_dir").read_text().strip() == str(one.resolve())


def test_same_named_properties_decks_get_their_own_scratch(tmp_path):
    scratch = tmp_path / "scr"
    scratch.mkdir()
    env = {"SCRATCH": str(scratch), "USER": NO_HPCC_USER}
    cwds = []
    for name in ("one", "two"):
        d = _folder(tmp_path, name, "x_band.d3", "BAND\nEND\n")
        (d / "x_band.f9").write_text(f"wavefunction of {name}")
        r = _run(tmp_path, _generate(d, "prop", "x_band"), env)
        assert r.returncode == 0, r.stdout + r.stderr
        cwds.append(_stub(d, "x_band")["CWD"])
    assert cwds[0] == str(scratch / "crys23" / "prop" / "x_band")
    assert cwds[1] != cwds[0] and "/crys23/prop/.mace_by_dir/" in cwds[1]


def test_restart_files_are_not_carried_over_from_another_folders_directory(tmp_path):
    """one ran under an earlier MACE (no ownership record), two then claimed
    the shared directory: one's rerun moves to a directory of its own and
    must not bring two's OPTINFO.DAT, fort.20 and fort.9 along from the
    directory its .x.scratch still names."""
    scratch = tmp_path / "scr"
    scratch.mkdir()
    env = {"SCRATCH": str(scratch), "USER": NO_HPCC_USER}
    one = _folder(tmp_path, "one", "x.d12", RESTART_DECK)
    two = _folder(tmp_path, "two", "x.d12", RESTART_DECK)
    shared = scratch / "crys23" / "x"
    r1 = _run(tmp_path, _generate(one, "crystal", "x"), env)
    assert r1.returncode == 0, r1.stdout + r1.stderr
    (shared / ".mace_submit_dir").unlink()                       # an earlier MACE wrote none
    r2 = _run(tmp_path, _generate(two, "crystal", "x"), env)
    assert r2.returncode == 0, r2.stdout + r2.stderr
    assert _stub(two, "x")["CWD"] == str(shared)
    for name in ("OPTINFO.DAT", "fort.20", "fort.9"):
        (shared / name).write_text(f"{name} of two/x")
    r3 = _run(tmp_path, one / "x.sh", env)
    assert r3.returncode == 0, r3.stdout + r3.stderr
    cwd3 = Path(_stub(one, "x")["CWD"])
    assert cwd3 != shared
    assert "brought OPTINFO.DAT" not in r3.stdout, r3.stdout
    assert "belongs to x in" in r3.stdout
    for name in ("OPTINFO.DAT", "fort.20"):
        assert not (cwd3 / name).exists() or "of two" not in (cwd3 / name).read_text()
    assert (shared / "OPTINFO.DAT").read_text() == "OPTINFO.DAT of two/x"


def test_the_ownership_record_is_refreshed_each_run(tmp_path):
    """A record lost from the deck's own directory (or a purged scratch) is
    written again by the next run, so the directory stays the deck's."""
    scratch = tmp_path / "scr"
    scratch.mkdir()
    env = {"SCRATCH": str(scratch), "USER": NO_HPCC_USER}
    one = _folder(tmp_path, "one", "x.d12", RESTART_DECK)
    shared = scratch / "crys23" / "x"
    r1 = _run(tmp_path, _generate(one, "crystal", "x"), env)
    assert r1.returncode == 0, r1.stdout + r1.stderr
    (shared / ".mace_submit_dir").unlink()
    r2 = _run(tmp_path, one / "x.sh", env)
    assert r2.returncode == 0, r2.stdout + r2.stderr
    assert (shared / ".mace_submit_dir").read_text().strip() == str(one.resolve())
    import shutil
    shutil.rmtree(scratch / "crys23")                             # scratch purged
    r3 = _run(tmp_path, one / "x.sh", env)
    assert r3.returncode == 0, r3.stdout + r3.stderr
    assert _stub(one, "x")["CWD"] == str(shared)
    assert (shared / ".mace_submit_dir").read_text().strip() == str(one.resolve())
