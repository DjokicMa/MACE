"""A properties job runs on the .f9 next to its deck and copies back only what
it wrote.

The properties job script staged into a scratch directory it never emptied,
copied $JOB.f9 there without checking, and copied BAND.DAT, fort.25,
DOSS.DAT, ... back unconditionally. A run whose .f9 was missing then ran
Pproperties on the fort.9 an earlier run left behind, and a run that failed
copied the earlier run's BAND.DAT back as its own result. The SCF script
copied an old fort.9 back over $JOB.f9 the same way.

`mace submit` refuses a .d3 whose .f9 is missing or empty before anything is
queued.

The scripts are generated by the real generators and run with bash, with a
stub mpirun; `mace submit` runs as a subprocess against tests/fake_slurm.py.
"""
import os
import stat
import subprocess
from pathlib import Path

from fake_slurm import FakeSlurm
from test_array_default_path_golden import BAND_D3
from test_scratch_guard import DECK, NO_HPCC_USER, _generate
from test_site_jobscript import _env, _mace

STUB = """#!/bin/bash
# Stand-in for mpirun: record the fort.9 CRYSTAL would read; STUB_WRITES
# names the result files this run writes.
echo "F9=$(cat fort.9 2>/dev/null || echo missing)" >> "$DIR/$JOB.stub"
# (a moment after the job script start marker, as any real run is)
sleep 0.2
for f in $STUB_WRITES; do echo "$f from $(cat fort.9 2>/dev/null)" > "$f"; done
"""


def _run(tmp_path: Path, script: Path, scratch: Path, **extra):
    stubs = tmp_path / "stubs"
    stubs.mkdir(exist_ok=True)
    for name, text in (("mpirun", STUB), ("python", "#!/bin/bash\nexit 0\n")):
        p = stubs / name
        p.write_text(text)
        p.chmod(p.stat().st_mode | stat.S_IEXEC)
    env = {"PATH": f"{stubs}:/usr/bin:/bin", "HOME": str(tmp_path), "SLURM_SUBMIT_DIR": str(script.parent),
           "SLURM_NTASKS": "1", "EBROOTCRYSTAL": str(tmp_path), "SCRATCH": str(scratch),
           "USER": NO_HPCC_USER}
    env.update(extra)
    return subprocess.run(["bash", str(script)], cwd=script.parent, env=env,
                          capture_output=True, text=True, timeout=60)


def _stub_lines(d: Path, job: str):
    f = d / f"{job}.stub"
    return f.read_text().splitlines() if f.is_file() else []


def test_failed_rerun_does_not_copy_back_the_earlier_results(tmp_path):
    d = tmp_path / "job"
    d.mkdir()
    (d / "si_band.d3").write_text("BAND\nEND\n")
    (d / "si_band.f9").write_text("wavefunction 1")
    scratch = tmp_path / "scr"
    script = _generate(d, "prop", "si_band")
    r = _run(tmp_path, script, scratch, STUB_WRITES="BAND.DAT fort.25")
    assert r.returncode == 0, r.stdout + r.stderr
    assert (d / "si_band.BAND.DAT").read_text() == "BAND.DAT from wavefunction 1\n"
    assert (d / "si_band.f25").is_file()

    # the second run fails before writing anything: nothing comes back
    (d / "si_band.BAND.DAT").unlink()
    (d / "si_band.f25").unlink()
    (d / "si_band.f9").write_text("wavefunction 2")
    r = _run(tmp_path, script, scratch, STUB_WRITES="")
    assert r.returncode == 0, r.stdout + r.stderr
    assert _stub_lines(d, "si_band")[-1] == "F9=wavefunction 2"
    assert not (d / "si_band.BAND.DAT").exists()
    assert not (d / "si_band.f25").exists()
    assert "cannot stat" not in r.stdout + r.stderr          # no copy of a file that is not there
    # Pproperties did not rewrite fort.9: the .f9 next to the deck is left alone
    assert (d / "si_band.f9").read_text() == "wavefunction 2"


def test_missing_or_empty_f9_stops_before_properties_run(tmp_path):
    d = tmp_path / "job"
    d.mkdir()
    (d / "si_band.d3").write_text("BAND\nEND\n")
    (d / "si_band.f9").write_text("wavefunction 1")
    scratch = tmp_path / "scr"
    script = _generate(d, "prop", "si_band")
    assert _run(tmp_path, script, scratch, STUB_WRITES="BAND.DAT").returncode == 0
    (d / "si_band.BAND.DAT").unlink()
    for state in ("missing", "empty"):
        if state == "missing":
            (d / "si_band.f9").unlink()
        else:
            (d / "si_band.f9").write_text("")
        r = _run(tmp_path, script, scratch, STUB_WRITES="BAND.DAT")
        assert r.returncode == 1, r.stdout + r.stderr
        assert len(_stub_lines(d, "si_band")) == 1                     # Pproperties never ran again
        assert f"si_band.f9 is {state}" in r.stdout
        assert f"si_band.f9 is {state}" in (d / "si_band.out").read_text()
        assert not (d / "si_band.BAND.DAT").exists()


def test_scf_script_copies_back_only_a_fort9_this_run_wrote(tmp_path):
    d = tmp_path / "job"
    d.mkdir()
    (d / "x.d12").write_text(DECK)
    scratch = tmp_path / "scr"
    job_dir = scratch / "crys23" / "x"
    job_dir.mkdir(parents=True)
    (job_dir / "fort.9").write_text("left by an earlier run")
    os.utime(job_dir / "fort.9", (1_700_000_000, 1_700_000_000))
    script = _generate(d, "crystal", "x")
    r = _run(tmp_path, script, scratch, STUB_WRITES="")         # CRYSTAL stopped before writing fort.9
    assert r.returncode == 0, r.stdout + r.stderr
    assert not (d / "x.f9").exists()
    r = _run(tmp_path, script, scratch, STUB_WRITES="fort.9")
    assert (d / "x.f9").read_text().startswith("fort.9 from")


def _submit_env(tmp_path):
    fake = FakeSlurm(tmp_path / "fs")
    env = _env(tmp_path, PATH=fake.env["PATH"], FAKE_SLURM_STATE=fake.env["FAKE_SLURM_STATE"],
               FAKE_SLURM_LOG=fake.env["FAKE_SLURM_LOG"])
    return env, fake


def test_submit_refuses_a_d3_without_its_f9(tmp_path):
    env, fake = _submit_env(tmp_path)
    d = tmp_path / "decks"
    d.mkdir()
    (d / "a_band.d3").write_text(BAND_D3)
    (d / "b_band.d3").write_text(BAND_D3)
    (d / "b_band.f9").write_text("wavefunction")
    (d / "c_band.d3").write_text(BAND_D3)
    (d / "c_band.f9").write_text("")
    p = _mace(tmp_path, env, "submit", "decks")
    out = p.stdout + p.stderr
    assert p.returncode == 1, out                            # not everything was submitted
    assert "2 of 3 job(s) not submitted" in out
    assert "a_band.f9 is missing" in out and "c_band.f9 is empty" in out
    scripts = [Path(c["script"]).name for c in fake.calls("sbatch")]
    assert scripts == ["b_band.sh"]
    # --nosubmit still writes every script (the .f9 may come later)
    p = _mace(tmp_path, env, "submit", "--nosubmit", "--overwrite-sh", "decks")
    assert p.returncode == 0, p.stdout + p.stderr
    assert all((d / f"{n}_band.sh").is_file() for n in "abc")


def test_scf_script_copies_back_an_scfout_log_this_run_wrote(tmp_path):
    """SCFOUT.LOG (an optimization's later points' SCF cycles) comes back as
    <job>.SCFOUT.LOG, only when this run wrote it: an earlier run's in the scratch
    directory, or none, leaves the job folder alone."""
    d = tmp_path / "job"
    d.mkdir()
    (d / "x.d12").write_text(DECK)
    scratch = tmp_path / "scr"
    job_dir = scratch / "crys23" / "x"
    job_dir.mkdir(parents=True)
    (job_dir / "SCFOUT.LOG").write_text("left by an earlier run")
    os.utime(job_dir / "SCFOUT.LOG", (1_700_000_000, 1_700_000_000))
    script = _generate(d, "crystal", "x")
    r = _run(tmp_path, script, scratch, STUB_WRITES="fort.9")       # an SP: no SCFOUT.LOG of its own
    assert r.returncode == 0, r.stdout + r.stderr
    assert not (d / "x.SCFOUT.LOG").exists()
    r = _run(tmp_path, script, scratch, STUB_WRITES="fort.9 SCFOUT.LOG")
    assert r.returncode == 0, r.stdout + r.stderr
    assert (d / "x.SCFOUT.LOG").read_text().startswith("SCFOUT.LOG from")
