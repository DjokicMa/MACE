"""The properties job script brings an ORBITALS run's Molden files back.

ORBITALS writes <root>.molden (a molecule) or <root>_<k>_K<ijk>_real.molden
and ..._complex.molden per k point, under the root named in the deck. MACE
writes <deck stem>_orb there; the script stages a renamed deck with its own
job's root (a workflow step, a copy by hand), copies ${JOB}_orb*.molden back
and nothing else of the run (no fort.*.peN).

The script is generated by the real generator and run with bash, with a stub
mpirun that writes what Pproperties would.
"""
import stat
import subprocess
from pathlib import Path

from test_scratch_guard import NO_HPCC_USER, _generate

STUB = """#!/bin/bash
# Stand-in for Pproperties: the Molden files under the deck's root, per-rank dumps
root=$(awk 'f { print; exit } toupper($1) == "ORBITALS" { f = 1 }' INPUT)
echo "ROOT=$root" > "$DIR/$JOB.stub"
cp INPUT "$DIR/$JOB.staged"
for k in $STUB_KPOINTS; do [ "$k" = NONE ] && k=; echo "[Molden Format]" > "${root}${k}.molden"; done
echo dump > fort.33.pe0
echo " TTTTTTTTTTTTTTTTTTTTTTTTTTTTTT ORBITALS    TELAPSE        0.19 TCPU        0.15"
"""


def _job(tmp_path, deck_name, deck_text, kpoints):
    d = tmp_path / "job"
    d.mkdir()
    (d / f"{deck_name}.d3").write_text(deck_text)
    (d / f"{deck_name}.f9").write_text("wavefunction")
    script = _generate(d, "prop", deck_name)
    stubs = tmp_path / "stubs"
    stubs.mkdir()
    for name, text in (("mpirun", STUB), ("python", "#!/bin/bash\nexit 0\n")):
        p = stubs / name
        p.write_text(text)
        p.chmod(p.stat().st_mode | stat.S_IEXEC)
    env = {"PATH": f"{stubs}:/usr/bin:/bin", "HOME": str(tmp_path), "SLURM_SUBMIT_DIR": str(d),
           "SLURM_NTASKS": "1", "EBROOTCRYSTAL": str(tmp_path), "SCRATCH": str(tmp_path / "scr"),
           "USER": NO_HPCC_USER, "STUB_KPOINTS": kpoints}
    r = subprocess.run(["bash", str(script)], cwd=d, env=env, capture_output=True, text=True, timeout=60)
    return d, script, r


def test_periodic_files_come_back_and_nothing_else(tmp_path):
    deck = "NEWK\n2 12\n1 0\nORBITALS\nsi_orbitals_orb\n1\n0\nEND"
    d, script, r = _job(tmp_path, "si_orbitals", deck, "_00001_K000_real _00002_K100_real _00002_K100_complex")
    assert r.returncode == 0, r.stdout + r.stderr
    assert sorted(p.name for p in d.glob("*.molden")) == [
        "si_orbitals_orb_00001_K000_real.molden", "si_orbitals_orb_00002_K100_complex.molden",
        "si_orbitals_orb_00002_K100_real.molden"]
    assert not list(d.glob("fort.*"))
    assert (d / "si_orbitals.d3").read_text() == deck            # the deck is never touched


def test_molecule_file_comes_back(tmp_path):
    deck = "NEWK\n1 0\nORBITALS\nh2o_orbitals_orb\n0\n0\nEND"
    d, _, r = _job(tmp_path, "h2o_orbitals", deck, "NONE")       # one file, no k suffix
    assert r.returncode == 0, r.stdout + r.stderr
    assert [p.name for p in d.glob("*.molden")] == ["h2o_orbitals_orb.molden"]


def test_a_renamed_deck_runs_under_its_job_root(tmp_path):
    # written as mat_orbitals.d3 (root mat_orbitals_orb), submitted as mat_orbitals2.d3
    deck = "NEWK\n2 12\n1 0\nORBITALS\nmat_orbitals_orb\n1\n0\nEND"
    d, _, r = _job(tmp_path, "mat_orbitals2", deck, "_00001_K000_real")
    assert r.returncode == 0, r.stdout + r.stderr
    assert (d / "mat_orbitals2.stub").read_text().strip() == "ROOT=mat_orbitals2_orb"
    assert [p.name for p in d.glob("*.molden")] == ["mat_orbitals2_orb_00001_K000_real.molden"]
    assert (d / "mat_orbitals2.d3").read_text() == deck
    assert (d / "mat_orbitals2.staged").read_text() == deck.replace("mat_orbitals_orb", "mat_orbitals2_orb")


def test_no_files_no_copy_errors(tmp_path):
    deck = "NEWK\n1 0\nORBITALS\nx_orbitals_orb\n0\n0\nEND"
    d, _, r = _job(tmp_path, "x_orbitals", deck, "")
    assert r.returncode == 0, r.stdout + r.stderr
    assert not list(d.glob("*.molden")) and "cannot stat" not in r.stdout + r.stderr


def test_other_decks_are_staged_as_they_are(tmp_path):
    deck = "NEWK\n8 16\n1 0\nDOSS\n0 100 -1 -1 1 14 0\n-0.5 0.5\nEND"
    d, _, r = _job(tmp_path, "si_doss", deck, "")
    assert r.returncode == 0, r.stdout + r.stderr
    assert (d / "si_doss.stub").read_text().strip() == "ROOT="
    assert (d / "si_doss.staged").read_text() == deck


def test_only_this_jobs_molden_names_come_back(tmp_path):
    # a file under the root but not of the ORBITALS naming stays in scratch
    deck = "NEWK\n2 12\n1 0\nORBITALS\nsi_orb\n1\n0\nEND"
    d, _, r = _job(tmp_path, "si", deck, "_00001_K000_real itals_orb_00001_K000_real X")
    assert r.returncode == 0, r.stdout + r.stderr
    assert sorted(p.name for p in d.glob("*.molden")) == ["si_orb_00001_K000_real.molden"]
    # moved, not copied: scratch keeps only the files that were not this job's
    left = sorted(p.name for p in (tmp_path / "scr").rglob("*.molden"))
    assert left == ["si_orbX.molden", "si_orbitals_orb_00001_K000_real.molden"]
